// Standard Raspberry Pi HAT outline: 65.0 mm (W) x 56.0 mm (H), 3.0 mm rounded corners,
// 4x M2.5 mounting holes on 58.0 x 49.0 mm pitch (3.5 mm edge inset).
// Coordinate system: origin (0, 0) at top-left corner; +X right (0..65 mm), +Y down (0..56 mm).

